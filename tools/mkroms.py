#!/usr/bin/env python3
"""Build roms/cp300_roms_pkg.vhd from the CP-300 ROM dumps.

    python tools/mkroms.py

The CP-300 (board revision before 2.3) has four 2732 EPROMs for the system
ROM (CI-28..31) and a 2716 character generator (CI-59):

    900-61.BIN  4 KB  0000-0FFF
    900-62.BIN  4 KB  1000-1FFF
    900-63.BIN  4 KB  2000-2FFF
    900-64.BIN  4 KB  3000-37FF (decoder CI-44 maps 3800-3FFF to keyboard/video)
    900-65.BIN  2 KB  character generator, address = code * 8 + scan line

The generated package is synthesized by Quartus and read by GHDL. It holds
copyrighted ROM contents, so it is not committed.
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ROMS = os.path.join(ROOT, "roms")
OUT = os.path.join(ROMS, "cp300_roms_pkg.vhd")

IMAGES = [
    ("EPROM_900_61", "900-61.BIN", 4096),
    ("EPROM_900_62", "900-62.BIN", 4096),
    ("EPROM_900_63", "900-63.BIN", 4096),
    ("EPROM_900_64", "900-64.BIN", 4096),
    ("CHARGEN_900_65", "900-65.BIN", 2048),
]


def load(name, size):
    path = os.path.join(ROMS, name)
    if not os.path.isfile(path):
        sys.exit(f"error: {os.path.normpath(path)} not found (dump it from the CP-300 board)")
    with open(path, "rb") as f:
        data = f.read()
    if len(data) != size:
        sys.exit(f"error: {name} is {len(data)} bytes, expected {size}")
    # A 2732 read with A11 stuck (e.g. as a 2716) gives two identical halves.
    # Only 900-64 may legitimately look like that: its upper half is unreachable.
    if size == 4096 and data[:2048] == data[2048:] and name != "900-64.BIN":
        print(f"warning: {name} has two identical 2 KB halves: probably dumped "
              f"with A11 stuck, re-read it as a 2732")
    return data


def constant(const, typ, data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ",".join(f'x"{b:02X}"' for b in data[i:i + 16]))
    return f"  constant {const} : {typ} := (\n" + ",\n".join(rows) + "\n  );\n"


def main():
    out = [
        "-- Generated by tools/mkroms.py from the CP-300 ROM dumps. Do not edit or commit.\n",
        "library ieee;\nuse ieee.std_logic_1164.all;\n\n",
        "package cp300_roms_pkg is\n",
        "  type rom4k_t is array(0 to 4095) of std_logic_vector(7 downto 0);\n",
        "  type rom2k_t is array(0 to 2047) of std_logic_vector(7 downto 0);\n\n",
    ]
    for const, name, size in IMAGES:
        out.append(constant(const, "rom4k_t" if size == 4096 else "rom2k_t", load(name, size)))
    out.append("end package;\n")
    with open(OUT, "w") as f:
        f.writelines(out)
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()

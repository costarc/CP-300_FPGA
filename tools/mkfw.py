#!/usr/bin/env python3
"""Turn the IO controller firmware image into rtl/io/io_fw_pkg.vhd.

    python tools/mkfw.py firmware/out/io_fw.ihx [rtl/io/io_fw_pkg.vhd]

The 16 KB ROM of io_ctrl is a constant array in a package, the same way
the CP-300 ROMs are, so Quartus and GHDL both read it.
"""
import os
import sys

SIZE = 16384


def load(path):
    """Intel HEX (SDCC .ihx) or raw binary; only addresses below the ROM size are used."""
    if not path.endswith(".ihx"):
        return open(path, "rb").read()
    mem = bytearray(SIZE)
    top = 0
    for line in open(path):
        line = line.strip()
        if not line.startswith(":"):
            continue
        n, addr, typ = int(line[1:3], 16), int(line[3:7], 16), int(line[7:9], 16)
        if typ != 0:
            continue
        for i in range(n):
            a = addr + i
            if a >= SIZE:
                sys.exit(f"error: code/data at {a:04X} is past the ROM")
            mem[a] = int(line[9 + 2 * i:11 + 2 * i], 16)
            top = max(top, a + 1)
    return bytes(mem[:top])


def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "io", "io_fw_pkg.vhd")
    data = load(src)
    if len(data) > SIZE:
        sys.exit(f"error: firmware is {len(data)} bytes, the ROM holds {SIZE}")
    used = len(data)
    data = data.ljust(SIZE, b"\xff")
    with open(dst, "w", newline="\n") as f:
        f.write("-- Generated by tools/mkfw.py from firmware/. Do not edit.\n")
        f.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage io_fw_pkg is\n")
        f.write(f"  type fw_rom_t is array(0 to {SIZE - 1}) of std_logic_vector(7 downto 0);\n")
        f.write("  constant FW_ROM : fw_rom_t := (\n")
        for i in range(0, SIZE, 16):
            row = ",".join(f'x"{b:02X}"' for b in data[i:i + 16])
            f.write(f"    {row}{',' if i + 16 < SIZE else ''}\n")
        f.write("  );\nend package;\n")
    print(f"{dst}: {used} bytes of code")


if __name__ == "__main__":
    main()
